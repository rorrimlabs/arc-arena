/** The timesheet: one row per person per day of the period, as the server counted it. */
export function timesheetCsv(lines: readonly RunLine[], meta: PayrollReportMeta): string {
  const body = [...lines]
    .sort((a, b) => a.staffName.localeCompare(b.staffName))
    .flatMap((l) =>
      l.days.map((d) =>
        [
          textCell(l.staffName),
          payTypeLabel(l.payType),
          d.day,
          weekdayOf(d.day),
          textCell(dayStatus(d.status).label),
          String(d.workedMin),
          hours(d.workedMin),
          String(d.extraMin),
          d.late ? 'Yes' : '',
          d.early ? 'Yes' : '',
          count(d.presentUnits),
          count(d.absentUnits),
          count(d.leavePaid),
          count(d.leaveLop),
          textCell(d.holiday ?? ''),
          textCell(d.flags.map(dayFlagLabel).join('; ')),
        ].join(','),
      ),
    );
  return (
    [
      ...header(meta, 'Timesheet', [
        'Worked = clocked minutes less the break, rounded as the arena’s working-hours rules say. Extra = minutes beyond the standard day, and every minute on a holiday or week off.',
      ]),
      TIMESHEET_HEAD.map((h) => textCell(h)).join(','),
      ...body,
    ].join('\n') + '\n'
  );
}

const CODES: readonly { code: DeductionCode; label: string }[] = [
  { code: 'absent', label: 'Absent' },
  { code: 'lop_leave', label: 'LOP leave' },
  { code: 'half_day', label: 'Half-day' },
  { code: 'late', label: 'Late' },
];

export const SUMMARY_HEAD = [
  'Staff',
  'Pay type',
  'Rates',
  'Scheduled days',
  'Present',
  'Late',
  'Half-days',
  'Absent',
  'Paid leave',
  'LOP leave',
  'Holidays',
  'Week offs',
  'Worked (h)',
  'Regular (h)',
  'Extra (h)',
  'Base (₹)',
  'Extra hours pay (₹)',
  'Gross (₹)',
  ...CODES.flatMap((c) => [`${c.label} suggested (₹)`, `${c.label} kept`, `${c.label} note`]),
  'Deductions applied (₹)',
  'Adjustments',
  'Adjustments (₹)',
  'Net (₹)',
  'Notes',
];

function ratesText(l: RunLine): string {
  return l.rates
    .map(
      (r) =>
        `${moneyCell(r.basePaise)} ${r.payType} from ${r.effectiveFrom}${r.extraHoursPaid ? ' (extra hours paid)' : ''}`,
    )
    .join('; ');
}

function adjustmentsText(list: readonly SalaryAdjustment[]): string {
  return list
    .map(
      (a) =>
        `${adjustmentLabel(a.kind)} ${moneyCell(a.amountPaise)} (${a.note})${isReversed(a, list) ? ' [reversed]' : ''}`,
    )
    .join('; ');
}

/**
 * The period summary: one row per person with every count, hours and money column, each
 * suggested deduction (kept or waived, with the note) and each adjustment; then a totals row.
 */
export function summaryCsv(
  lines: readonly RunLine[],
  adjustments: readonly SalaryAdjustment[],
  meta: PayrollReportMeta,
): string {
  const ordered = [...lines].sort((a, b) => a.staffName.localeCompare(b.staffName));
  const body = ordered.map((l) => {
    const c = l.dayCounts;
    const own = adjustments.filter((a) => a.staffId === l.staffId);
    return [
      textCell(l.staffName),
      payTypeLabel(l.payType),
      textCell(ratesText(l)),
      count(c.scheduled),
      count(c.present),
      count(c.late),
      count(c.halfDay),
      count(c.absent),
      count(c.paidLeave),
      count(c.lopLeave),
      count(c.holiday),
      count(c.weekOff),
      hours(l.workedMin),
      hours(l.regularMin),
      hours(l.extraMin),
      moneyCell(l.basePaise),
      moneyCell(l.extraPaise),
      moneyCell(l.grossPaise),
      ...CODES.flatMap(({ code }) => {
        const d = l.deductions.find((x) => x.code === code);
        return d
          ? [moneyCell(d.amountPaise), d.applied ? 'Kept' : 'Waived', textCell(d.note ?? '')]
          : ['', '', ''];
      }),
      moneyCell(l.deductionsPaise),
      textCell(adjustmentsText(own)),
      moneyCell(l.adjustmentsPaise),
      moneyCell(l.netPaise),
      textCell(l.notes.join('; ')),
    ].join(',');
  });
  const sum = (f: (l: RunLine) => number) => lines.reduce((n, l) => n + f(l), 0);
  const total = Array<string>(SUMMARY_HEAD.length).fill('');
  total[0] = textCell(`Total — ${lines.length} ${lines.length === 1 ? 'person' : 'people'}`);
  total[15] = moneyCell(sum((l) => l.basePaise));
  total[16] = moneyCell(sum((l) => l.extraPaise));
  total[17] = moneyCell(sum((l) => l.grossPaise));
  total[SUMMARY_HEAD.length - 5] = moneyCell(sum((l) => l.deductionsPaise));
  total[SUMMARY_HEAD.length - 3] = moneyCell(sum((l) => l.adjustmentsPaise));
  total[SUMMARY_HEAD.length - 2] = moneyCell(sum((l) => l.netPaise));
  return (
    [
      ...header(meta, 'Pay summary', [
        'Every figure is the server’s. A suggested deduction counts only when kept; deductions are capped at gross. Net = gross − deductions applied + adjustments.',
      ]),
      SUMMARY_HEAD.map((h) => textCell(h)).join(','),
      ...body,
      total.join(','),
    ].join('\n') + '\n'
  );
}
