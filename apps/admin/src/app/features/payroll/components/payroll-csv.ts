/** What a payroll export covers and who made it: the block at the top of the file. */
export interface PayrollReportMeta {
  readonly arena: string;
  readonly run: SalaryRun;
  readonly generatedAt: Date;
  /** "Name <email>" of the signed-in login. */
  readonly generatedBy: string | null;
}

/** Paise as rupees with two decimals, from integers (no symbol, no grouping). */
export function moneyCell(paise: number): string {
  const p = Math.round(paise);
  const abs = Math.abs(p);
  return `${p < 0 ? '-' : ''}${Math.trunc(abs / 100)}.${String(abs % 100).padStart(2, '0')}`;
}

function hours(minutes: number): string {
  return (minutes / 60).toFixed(2);
}

function count(n: number): string {
  return String(Math.round(n * 100) / 100);
}

function header(meta: PayrollReportMeta, title: string, notes: readonly string[]): string[] {
  const r = meta.run;
  const at = meta.generatedAt;
  return [
    [textCell(`${meta.arena} — ${title}`)],
    ['Arena', textCell(meta.arena)],
    ['Period', textCell(`${r.periodStart} to ${r.periodEnd} (IST calendar days)`)],
    ['Status', textCell(runStatus(r.status).label)],
    ['Time zone', textCell('Asia/Kolkata (IST, UTC+05:30)')],
    ['Generated', textCell(`${formatIsoDate(at)} ${formatHm(at)} IST (${at.toISOString()})`)],
    ['Generated by', textCell(meta.generatedBy ?? '')],
    ...notes.map((n) => ['Note', textCell(n)]),
    [],
  ].map((cells) => cells.join(','));
}

