/** What a report covers and who made it: the block at the top of every export. */
export interface ReportMeta {
  readonly arena: string;
  readonly period: SalesPeriod;
  readonly generatedAt: Date;
  /** "Name <email>" of the signed-in login. */
  readonly generatedBy: string | null;
  /** The list's filters, when any ("bills paid by UPI; search "rift""). */
  readonly filters: string | null;
}

const TIME_ZONE = 'Asia/Kolkata (IST, UTC+05:30)';

/**
 * A text cell. Values that a spreadsheet would run as a formula (=, +, -, @, tab, return) get a
 * leading apostrophe, so a member name typed on the floor can never execute in Excel or Sheets;
 * cells with a comma, quote or line break are quoted.
 */
export function textCell(value: string | null | undefined): string {
  let s = value ?? '';
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** Paise as rupees with two decimals (no symbol, no grouping), a number to spreadsheets. */
function money(paise: number): string {
  return (paise / 100).toFixed(2);
}

function hours(minutes: number): string {
  return (minutes / 60).toFixed(2);
}

function plural(n: number, noun: string): string {
  return `${n} ${noun}${n === 1 ? '' : 's'}`;
}

function row(cells: readonly string[]): string {
  return cells.join(',');
}

function header(meta: ReportMeta, title: string, notes: readonly string[]): string[] {
  const p = meta.period;
  const days = p.first === p.last ? p.first : `${p.first} to ${p.last}`;
  const at = meta.generatedAt;
  return [
    row([textCell(`${meta.arena} — ${title}`)]),
    row(['Arena', textCell(meta.arena)]),
    row(['Period', textCell(`${days} (IST calendar days; a bill belongs to the day it closed)`)]),
    row(['Time zone', textCell(TIME_ZONE)]),
    row(['Generated', textCell(`${formatIsoDate(at)} ${formatHm(at)} IST (${at.toISOString()})`)]),
    row(['Generated by', textCell(meta.generatedBy ?? '')]),
    ...(meta.filters ? [row(['Filters', textCell(meta.filters)])] : []),
    ...notes.map((n) => row(['Note', textCell(n)])),
    '',
  ];
}

