function status(b: Bill): string {
  if (b.voided) return 'Void';
  switch (b.paymentStatus) {
    case 'waived':
      return 'Waived';
    case 'unpaid':
      return 'Unpaid';
    case 'partial':
      return 'Part paid';
    default:
      return 'Paid';
  }
}

function at(iso: string | null): string {
  return iso ? `${formatIsoDate(iso)} ${formatHm(iso)}` : '';
}

/** Total columns of a set of bills, in BILL_HEAD order from "Minutes" (blanks elsewhere). */
function totalsRow(label: string, bills: readonly Bill[], counts: boolean): string {
  const s = summarize(bills.map((b) => (counts ? b : { ...b, voided: false })));
  const minutes = bills.reduce((n, b) => n + playedMinutes(b), 0);
  const playerMinutes = bills.reduce((n, b) => n + b.playerMinutes, 0);
  const cells = Array<string>(BILL_HEAD.length).fill('');
  cells[0] = textCell(label);
  cells[7] = String(minutes);
  cells[8] = hours(minutes);
  cells[13] = hours(playerMinutes);
  cells[16] = money(bills.reduce((n, b) => n + (b.billedPaise ?? 0), 0));
  cells[17] = counts ? money(s.expectedPaise) : money(0);
  PAY_METHODS.forEach((m, i) => (cells[18 + i] = money(s.byMethod[m])));
  cells[22] = money(s.takingsPaise);
  cells[23] = money(s.refundedPaise);
  cells[24] = counts ? money(s.duePaise) : money(0);
  cells[25] = counts ? money(s.writtenOffPaise) : money(0);
  return row(cells);
}

/**
 * The bills report: one row per bill, oldest first, numbered per business day, with the
 * spreadsheet's columns (players, player-hours, customer type, cash / UPI received, total paid,
 * expected, difference). Ends with two totals rows that match the Sales screen: the bills that
 * count, and the money still sitting on voided bills.
 */
export function billsCsv(bills: readonly Bill[], meta: ReportMeta): string {
  const numbers = dayNumbers(bills);
  const ordered = [...bills].sort(
    (a, b) =>
      formatIsoDate(a.at).localeCompare(formatIsoDate(b.at)) ||
      (numbers.get(a.id) ?? 0) - (numbers.get(b.id) ?? 0),
  );
  const rows = ordered.map((b) => {
    const minutes = playedMinutes(b);
    const net = (m: PayMethod) => money(b.methods[m] ?? 0);
    return row([
      formatIsoDate(b.at),
      String(numbers.get(b.id) ?? ''),
      b.ref,
      b.id,
      b.kind === 'group' ? 'Group' : 'Single',
      formatHm(b.startedAt),
      b.endedAt ? formatHm(b.endedAt) : '',
      String(minutes),
      hours(minutes),
      textCell(b.stations.join(' + ')),
      textCell(b.activities.join(' + ')),
      textCell(b.games.join(' + ')),
      String(b.players),
      hours(b.playerMinutes),
      textCell(b.customer),
      customerType(b),
      money(b.billedPaise ?? 0),
      money(b.voided ? 0 : (b.billedPaise ?? 0)),
      ...PAY_METHODS.map(net),
      money(b.paidPaise),
      money(b.refundedPaise),
      money(duePaise(b)),
      money(writtenOffPaise(b)),
      status(b),
      textCell(b.voidReason),
      textCell(b.voidedBy),
      at(b.voidedAt),
      textCell(b.startedBy),
      at(b.recordedAt),
    ]);
  });
  const counted = bills.filter((b) => !b.voided);
  const voided = bills.filter((b) => b.voided);
  return (
    [
      ...header(meta, 'Sales report (bills)', [
        'Expected = final bills that count (not voided), waived ones included. Collected = payments minus refunds on them, whenever received. Outstanding = still owed on bills not waived. Written off = what a waive left unpaid.',
        'Cash / UPI / Card / Other are net of refunds. Expected + overpaid = collected + outstanding + written off.',
        'No. numbers each business day’s bills in start order; Bill ID is the permanent reference.',
      ]),
      row(BILL_HEAD.map((h) => textCell(h))),
      ...rows,
      totalsRow(`Total — ${plural(counted.length, 'bill')} (voided bills excluded)`, counted, true),
      ...(voided.length
        ? [totalsRow(`On ${plural(voided.length, 'voided bill')} (not in takings)`, voided, false)]
        : []),
    ].join('\n') + '\n'
  );
}

