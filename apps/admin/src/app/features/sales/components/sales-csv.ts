/**
 * The payments ledger of the same bills: one row per payment or refund (refunds negative), in
 * the order the server recorded them, then the net per method. Its total equals the bills
 * report's collected plus what is on voided bills.
 */
export function paymentsCsv(bills: readonly Bill[], meta: ReportMeta): string {
  const entries = bills.flatMap((b) => b.payments.map((p) => ({ b, p })));
  entries.sort(
    (x, y) =>
      Date.parse(x.p.at) - Date.parse(y.p.at) ||
      Number(y.p.refund) - Number(x.p.refund) ||
      x.p.id.localeCompare(y.p.id),
  );
  const rows = entries.map(({ b, p }) =>
    row([
      formatIsoDate(p.at),
      formatHm(p.at),
      b.ref,
      b.id,
      formatIsoDate(b.at),
      status(b),
      textCell(b.customer),
      methodName(p.method),
      p.correction
        ? p.refund
          ? 'Correction out'
          : 'Correction in'
        : p.refund
          ? 'Refund'
          : 'Payment',
      money(p.amountPaise),
      textCell(p.reason),
      textCell(p.note),
      textCell(p.by),
      p.at,
    ]),
  );
  const net = (m: PayMethod) =>
    entries.filter(({ p }) => p.method === m).reduce((n, { p }) => n + p.amountPaise, 0);
  const total = entries.reduce((n, { p }) => n + p.amountPaise, 0);
  const totals = [
    ...PAY_METHODS.filter((m) => entries.some(({ p }) => p.method === m)).map((m) =>
      row([textCell(`Net ${methodName(m)}`), ...Array<string>(8).fill(''), money(net(m))]),
    ),
    row([textCell('Net total'), ...Array<string>(8).fill(''), money(total)]),
  ];
  return (
    [
      ...header(meta, 'Payments ledger', [
        'Every payment and refund of the bills in the bills report for this period (refunds are negative). A correction of the payment method is two rows, Correction out (old method) and Correction in (new method), with its reason; they are not refunds and net to zero.',
        'Received = when the server recorded it; a payment taken while a device was offline carries the time it synced.',
      ]),
      row(PAYMENT_HEAD.map((h) => textCell(h))),
      ...rows,
      ...totals,
    ].join('\n') + '\n'
  );
}
