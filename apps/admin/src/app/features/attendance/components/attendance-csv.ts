import { formatHm, formatIsoDate } from '../../../shared/time/ist';
import { textCell } from '../../sales/components/sales-csv';
import {
  LogRow,
  Punch,
  entryMinutes,
  flagLabel,
  reviewLabel,
  verdictLabel,
} from '../data/attendance.models';

/** What an attendance export covers and who made it: the block at the top of the file. */
export interface AttendanceReportMeta {
  readonly arena: string;
  readonly first: string;
  readonly last: string;
  readonly generatedAt: Date;
  /** "Name <email>" of the signed-in login. */
  readonly generatedBy: string | null;
  /** The list's filters, when any ("Priya Nair; outside; needs review"). */
  readonly filters: string | null;
}

export const ATTENDANCE_HEAD = [
  'Staff',
  'Work date',
  'In (IST)',
  'Out (IST)',
  'Minutes',
  'In verdict',
  'In distance (m)',
  'In accuracy (m)',
  'Out verdict',
  'Out distance (m)',
  'Out accuracy (m)',
  'Flags',
  'Review',
];

function at(iso: string | null): string {
  return iso ? `${formatIsoDate(iso)} ${formatHm(iso)}` : '';
}

function n(v: number | null | undefined): string {
  return v === null || v === undefined ? '' : String(Math.round(v));
}

function punchCells(p: Punch | null): string[] {
  return p ? [verdictLabel(p.geofence), n(p.distanceM), n(p.accuracyM)] : ['', '', ''];
}

/**
 * The attendance log as CSV: a block saying what it covers, then one row per entry, oldest
 * first. Server times in IST; minutes are out − in (blank for an entry still open); flags in
 * plain words.
 */
export function attendanceCsv(rows: readonly LogRow[], meta: AttendanceReportMeta): string {
  const days = meta.first === meta.last ? meta.first : `${meta.first} to ${meta.last}`;
  const g = meta.generatedAt;
  const head = [
    [textCell(`${meta.arena} — Attendance log`)],
    ['Arena', textCell(meta.arena)],
    ['Period', textCell(`${days} (IST calendar days; an entry belongs to the day it started)`)],
    ['Time zone', textCell('Asia/Kolkata (IST, UTC+05:30)')],
    ['Generated', textCell(`${formatIsoDate(g)} ${formatHm(g)} IST (${g.toISOString()})`)],
    ['Generated by', textCell(meta.generatedBy ?? '')],
    ...(meta.filters ? [['Filters', textCell(meta.filters)]] : []),
    [
      'Note',
      textCell(
        'Times are when the server recorded each clock-in and clock-out. An entry still open has no out time or minutes.',
      ),
    ],
  ].map((cells) => cells.join(','));
  const ordered = [...rows].sort(
    (a, b) =>
      a.entry.workDate.localeCompare(b.entry.workDate) ||
      Date.parse(a.entry.inAt) - Date.parse(b.entry.inAt),
  );
  const body = ordered.map((r) => {
    const e = r.entry;
    return [
      textCell(r.staffName),
      e.workDate,
      at(e.inAt),
      at(e.outAt),
      e.outAt ? String(entryMinutes(e, new Date(e.outAt))) : '',
      ...punchCells(r.inPunch),
      ...punchCells(r.outPunch),
      textCell(e.flags.map(flagLabel).join('; ')),
      textCell(reviewLabel(e.review)?.label ?? ''),
    ].join(',');
  });
  return (
    [...head, '', ATTENDANCE_HEAD.map((h) => textCell(h)).join(','), ...body].join('\n') + '\n'
  );
}
